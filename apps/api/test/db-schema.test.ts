import { randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import { afterAll, beforeAll, describe, expect, inject, it } from 'vitest';

const journalPath = fileURLToPath(
  new URL('../../../db/migrations/meta/_journal.json', import.meta.url),
);

const EXPECTED_TABLES = [
  'cards',
  'exercises',
  'goals',
  'hints',
  'mistake_categories',
  'mistake_patterns',
  'mistakes',
  'profiles',
  'refresh_tokens',
  'session_reports',
  'session_words',
  'sessions',
  'theory_links',
  'users',
  'utterances',
  'words',
];

// Format is `table.name` (names are auto-generated by Postgres for inline CHECKs).
// 0001 has 12 CHECKs (words_state_check is replaced by 0002, so it is counted once); 0002 adds 4 new ones, 0003 and 0004 add 1 each, 0005 adds none.
const EXPECTED_CHECKS = [
  'profiles.profiles_level_check',
  'goals.goals_status_check',
  'sessions.sessions_topic_source_check',
  'sessions.sessions_feedback_mode_check',
  'sessions.sessions_status_check',
  'utterances.utterances_role_check',
  'mistake_patterns.mistake_patterns_frequency_check',
  'words.words_state_check',
  'words.words_source_check',
  'hints.hints_kind_check',
  'cards.cards_interval_days_check',
  'exercises.exercises_kind_check',
  'mistakes.chk_mistakes_span',
  'utterances.utterances_analysis_status_check',
  'words.chk_words_times_used',
  'profiles.chk_profiles_interface_lang',
  'sessions.sessions_plan_check',
  'utterances.utterances_better_phrasings_check',
];

describe('DB schema after migrations', () => {
  let pool: pg.Pool;

  beforeAll(() => {
    pool = new pg.Pool({ connectionString: inject('testDatabaseUrl') });
  });

  afterAll(async () => {
    await pool.end();
  });

  it('[TC-00-01] the public schema has exactly the 16 expected tables', async () => {
    const { rows } = await pool.query<{ table_name: string }>(
      `SELECT table_name FROM information_schema.tables
       WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
       ORDER BY table_name COLLATE "C"`,
    );

    expect(rows.map((row) => row.table_name)).toEqual(
      [...EXPECTED_TABLES].sort(),
    );
    expect(rows).toHaveLength(16);
  });

  it('[TC-00-01] public has all expected CHECK constraints and no extra ones', async () => {
    const { rows } = await pool.query<{ check_name: string }>(
      `SELECT c.conrelid::regclass::text || '.' || c.conname AS check_name
       FROM pg_constraint c
       WHERE c.contype = 'c' AND c.connamespace = 'public'::regnamespace
       ORDER BY (c.conrelid::regclass::text || '.' || c.conname) COLLATE "C"`,
    );

    expect(rows.map((row) => row.check_name)).toEqual(
      [...EXPECTED_CHECKS].sort(),
    );
    expect(rows).toHaveLength(18);
  });

  it('[TC-00-01] words_state_check from 0002 allows the active state', async () => {
    const { rows } = await pool.query<{ definition: string }>(
      `SELECT pg_get_constraintdef(oid) AS definition FROM pg_constraint
       WHERE conname = 'words_state_check' AND conrelid = 'public.words'::regclass`,
    );

    expect(rows).toHaveLength(1);
    expect(rows[0]?.definition).toContain("'active'");
  });

  it('[TC-00-01] drizzle.__drizzle_migrations has one row per journal entry', async () => {
    const journal = JSON.parse(readFileSync(journalPath, 'utf8')) as {
      entries: unknown[];
    };
    const { rows } = await pool.query<{ count: string }>(
      'SELECT count(*) AS count FROM drizzle.__drizzle_migrations',
    );

    expect(journal.entries.length).toBeGreaterThan(0);
    expect(Number(rows[0]?.count)).toBe(journal.entries.length);
  });

  describe('session_words and report metadata (0005)', () => {
    it('[TC-00-01] session_words has a composite primary key and cascading foreign keys', async () => {
      const { rows } = await pool.query<{ definition: string }>(
        `SELECT pg_get_constraintdef(oid) AS definition FROM pg_constraint
         WHERE conrelid = 'public.session_words'::regclass AND contype IN ('p', 'f')
         ORDER BY contype DESC, pg_get_constraintdef(oid) COLLATE "C"`,
      );

      expect(rows.map((row) => row.definition)).toEqual([
        'PRIMARY KEY (session_id, word_id)',
        'FOREIGN KEY (session_id) REFERENCES sessions(id) ON DELETE CASCADE',
        'FOREIGN KEY (word_id) REFERENCES words(id) ON DELETE CASCADE',
      ]);
    });

    it('[TC-00-01] the new indexes cover the keyset order and the word foreign key', async () => {
      const { rows } = await pool.query<{
        indexname: string;
        indexdef: string;
      }>(
        `SELECT indexname, indexdef FROM pg_indexes
         WHERE schemaname = 'public'
           AND indexname IN ('idx_session_words_word', 'idx_words_user_created')
         ORDER BY indexname COLLATE "C"`,
      );

      expect(rows.map((row) => row.indexname)).toEqual([
        'idx_session_words_word',
        'idx_words_user_created',
      ]);
      expect(rows[0]?.indexdef).toContain('(word_id)');
      expect(rows[1]?.indexdef).toContain(
        '(user_id, created_at DESC, id DESC)',
      );
    });

    it('[TC-00-01] session_reports has nullable prompt_version and model columns', async () => {
      const { rows } = await pool.query<{
        column_name: string;
        is_nullable: string;
        data_type: string;
      }>(
        `SELECT column_name, is_nullable, data_type FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = 'session_reports'
           AND column_name IN ('prompt_version', 'model')
         ORDER BY column_name COLLATE "C"`,
      );

      expect(rows).toEqual([
        { column_name: 'model', is_nullable: 'YES', data_type: 'text' },
        {
          column_name: 'prompt_version',
          is_nullable: 'YES',
          data_type: 'text',
        },
      ]);
    });

    describe('with a user, session and word', () => {
      let userId: string;
      let sessionId: string;
      let wordId: string;

      beforeAll(async () => {
        const user = await pool.query<{ id: string }>(
          `INSERT INTO users (email, password_hash) VALUES ($1, 'x') RETURNING id`,
          [`${randomUUID()}@example.com`],
        );
        userId = user.rows[0]?.id ?? '';
        const session = await pool.query<{ id: string }>(
          `INSERT INTO sessions (user_id, topic, status) VALUES ($1, 'topic', 'finished') RETURNING id`,
          [userId],
        );
        sessionId = session.rows[0]?.id ?? '';
        const word = await pool.query<{ id: string }>(
          `INSERT INTO words (user_id, lemma) VALUES ($1, $2) RETURNING id`,
          [userId, `lemma-${randomUUID()}`],
        );
        wordId = word.rows[0]?.id ?? '';
      });

      afterAll(async () => {
        await pool.query('DELETE FROM users WHERE id = $1', [userId]);
      });

      const link = (session: string, word: string) =>
        pool.query(
          'INSERT INTO session_words (session_id, word_id) VALUES ($1, $2)',
          [session, word],
        );

      const countLinks = async (session: string) =>
        Number(
          (
            await pool.query<{ count: string }>(
              'SELECT count(*) FROM session_words WHERE session_id = $1',
              [session],
            )
          ).rows[0]?.count,
        );

      it('[TC-00-01] linking the same word to a session twice is rejected', async () => {
        await link(sessionId, wordId);

        await expect(link(sessionId, wordId)).rejects.toMatchObject({
          code: '23505',
          constraint: 'session_words_pkey',
        });
        expect(await countLinks(sessionId)).toBe(1);
      });

      it('[TC-00-01] a link to a missing session or word is rejected', async () => {
        await expect(link(randomUUID(), wordId)).rejects.toMatchObject({
          code: '23503',
        });
        await expect(link(sessionId, randomUUID())).rejects.toMatchObject({
          code: '23503',
        });
      });

      it('[TC-00-01] deleting the word removes its links but keeps the session', async () => {
        const other = await pool.query<{ id: string }>(
          `INSERT INTO words (user_id, lemma) VALUES ($1, $2) RETURNING id`,
          [userId, `lemma-${randomUUID()}`],
        );
        const otherWordId = other.rows[0]?.id ?? '';
        await link(sessionId, otherWordId);
        const before = await countLinks(sessionId);

        await pool.query('DELETE FROM words WHERE id = $1', [otherWordId]);

        expect(await countLinks(sessionId)).toBe(before - 1);
        const { rowCount } = await pool.query(
          'SELECT 1 FROM sessions WHERE id = $1',
          [sessionId],
        );
        expect(rowCount).toBe(1);
      });

      it('[TC-00-01] deleting the session removes its links but keeps the word', async () => {
        const session = await pool.query<{ id: string }>(
          `INSERT INTO sessions (user_id, topic, status) VALUES ($1, 'topic', 'finished') RETURNING id`,
          [userId],
        );
        const otherSessionId = session.rows[0]?.id ?? '';
        await link(otherSessionId, wordId);

        await pool.query('DELETE FROM sessions WHERE id = $1', [
          otherSessionId,
        ]);

        expect(await countLinks(otherSessionId)).toBe(0);
        const word = await pool.query('SELECT 1 FROM words WHERE id = $1', [
          wordId,
        ]);
        expect(word.rowCount).toBe(1);
      });
    });
  });

  describe('utterances better_phrasings (0004)', () => {
    let userId: string;
    let sessionId: string;

    beforeAll(async () => {
      const user = await pool.query<{ id: string }>(
        `INSERT INTO users (email, password_hash) VALUES ($1, 'x') RETURNING id`,
        [`${randomUUID()}@example.com`],
      );
      userId = user.rows[0]?.id ?? '';
      const session = await pool.query<{ id: string }>(
        `INSERT INTO sessions (user_id, topic, status) VALUES ($1, 'topic', 'finished') RETURNING id`,
        [userId],
      );
      sessionId = session.rows[0]?.id ?? '';
    });

    afterAll(async () => {
      await pool.query('DELETE FROM users WHERE id = $1', [userId]);
    });

    function insertUtterance(seq: number, betterPhrasings?: string) {
      return pool.query<{ better_phrasings: unknown }>(
        `INSERT INTO utterances (session_id, seq, role, text_verbatim, better_phrasings)
         VALUES ($1, $2, 'user', 'text', COALESCE($3::jsonb, '[]'::jsonb)) RETURNING better_phrasings`,
        [sessionId, seq, betterPhrasings ?? null],
      );
    }

    it('[TC-00-01] better_phrasings defaults to an empty array when omitted', async () => {
      const { rows } = await pool.query<{ better_phrasings: unknown }>(
        `INSERT INTO utterances (session_id, seq, role, text_verbatim)
         VALUES ($1, 1, 'user', 'text') RETURNING better_phrasings`,
        [sessionId],
      );

      expect(rows[0]?.better_phrasings).toEqual([]);
    });

    it('[TC-00-01] better_phrasings_check accepts an array and rejects other JSON types', async () => {
      const { rows } = await insertUtterance(
        2,
        '[{"original":"a","better":"b"}]',
      );
      expect(rows[0]?.better_phrasings).toEqual([
        { original: 'a', better: 'b' },
      ]);

      for (const [seq, value] of [
        [3, '{}'],
        [4, '"text"'],
        [5, 'null'],
      ] as const) {
        await expect(insertUtterance(seq, value)).rejects.toMatchObject({
          constraint: 'utterances_better_phrasings_check',
        });
      }
    });
  });

  describe('sessions plan and active-session index (0003)', () => {
    let userId: string;

    beforeAll(async () => {
      const { rows } = await pool.query<{ id: string }>(
        `INSERT INTO users (email, password_hash) VALUES ($1, 'x') RETURNING id`,
        [`${randomUUID()}@example.com`],
      );
      userId = rows[0]?.id ?? '';
    });

    afterAll(async () => {
      await pool.query('DELETE FROM users WHERE id = $1', [userId]);
    });

    function insertSession(status: string, plan: string | null) {
      return pool.query(
        `INSERT INTO sessions (user_id, topic, status, plan) VALUES ($1, 'topic', $2, $3::jsonb)`,
        [userId, status, plan],
      );
    }

    it('[TC-00-01] sessions_plan_check accepts NULL and an object with a questions array', async () => {
      await insertSession('finished', null);
      await insertSession('finished', JSON.stringify({ questions: [] }));
      await insertSession(
        'finished',
        JSON.stringify({ questions: ['Q1'], extra: 1 }),
      );
    });

    it.each([
      ['an array', '[]'],
      ['a string', '"questions"'],
      ['an object without questions', '{"topic":"x"}'],
      ['an object whose questions is not an array', '{"questions":"Q1"}'],
      ['JSON null', 'null'],
    ])('[TC-00-01] sessions_plan_check rejects %s', async (_name, plan) => {
      await expect(insertSession('finished', plan)).rejects.toMatchObject({
        constraint: 'sessions_plan_check',
      });
    });

    it('[TC-00-01] a second active session of the same user is rejected, finished ones are not', async () => {
      await insertSession('active', null);

      await expect(insertSession('active', null)).rejects.toMatchObject({
        code: '23505',
        constraint: 'sessions_one_active_per_user',
      });
      await insertSession('finished', null);
    });

    it('[TC-00-01] another user can have an active session at the same time', async () => {
      const { rows } = await pool.query<{ id: string }>(
        `INSERT INTO users (email, password_hash) VALUES ($1, 'x') RETURNING id`,
        [`${randomUUID()}@example.com`],
      );
      const otherId = rows[0]?.id;
      try {
        await pool.query(
          `INSERT INTO sessions (user_id, topic, status) VALUES ($1, 'topic', 'active')`,
          [otherId],
        );
      } finally {
        await pool.query('DELETE FROM users WHERE id = $1', [otherId]);
      }
    });
  });
});
